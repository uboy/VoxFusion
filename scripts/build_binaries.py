def _is_installed(package: str) -> bool:
    """Return True if *package* is importable in the current environment."""
    try:
        return importlib.util.find_spec(package.replace("-", "_")) is not None
    except (ImportError, ModuleNotFoundError, ValueError):
        return False


def _safe_find_spec(module_name: str):
    """Return `find_spec(module_name)` or `None` when parent modules are absent."""
    try:
        return importlib.util.find_spec(module_name)
    except (ImportError, ModuleNotFoundError, ValueError):
        return None


def _parse_backends(backends_arg: str) -> set[str]:
    """Return the normalised set of requested backend names.

    Accepts a comma-separated string such as ``"gigaam,breeze"`` or ``"all"``.
    ``"all"`` expands to every known backend.
    """
    known = {"whisper", "gigaam", "breeze", "parakeet"}
    raw = {b.strip().lower() for b in backends_arg.split(",") if b.strip()}
    if "all" in raw:
        return known
    unknown = raw - known
    if unknown:
        print(
            f"[backends] WARNING: unknown backend(s): {', '.join(sorted(unknown))}. "
            f"Known: {', '.join(sorted(known))}"
        )
    return raw


def _collect_all_packages(*, backends: set[str]) -> list[str]:
    """Return the list of packages that need --collect-all.

    Only packages that are actually installed are included so that
    PyInstaller does not fail on missing optional dependencies.
    """
    # Always needed: pyaudiowpatch ships native DLLs that must be collected.
    candidates = ["pyaudiowpatch"]

    needs_torch = backends & {"gigaam", "breeze", "parakeet"}

    # pyannote.audio pulls torch transitively; --collect-all triggers
    # PyInstaller's _collect_submodules('torch.distributed.optim') which
    # segfaults on Linux.  Only include pyannote when torch backends are
    # explicitly requested (they already collect-all torch anyway).
    if needs_torch and _is_installed("pyannote.audio"):
        candidates.append("pyannote.audio")
        print("[deps] --collect-all pyannote.audio  (ML diarization / speaker detect)")
    elif _is_installed("pyannote.audio"):
        print(
            "[deps] skipping --collect-all pyannote.audio (torch not in backends, avoids segfault)"
        )
    else:
        print(
            "[deps] WARNING: pyannote.audio not installed — ML diarization and speaker detect won't work"
        )

    needs_torch = backends & {"gigaam", "breeze", "parakeet"}
    needs_transformers = backends & {"gigaam", "breeze"}

    if needs_torch:
        if _is_installed("torch"):
            candidates.append("torch")
            print(f"[deps] --collect-all torch  (backends: {', '.join(sorted(needs_torch))})")
        else:
            print(
                f"[deps] WARNING: torch not installed — backends {', '.join(sorted(needs_torch))} won't work"
            )

    if needs_transformers:
        if _is_installed("transformers"):
            candidates.append("transformers")
            print(
                f"[deps] --collect-all transformers  (backends: {', '.join(sorted(needs_transformers))})"
            )
        else:
            print(
                f"[deps] WARNING: transformers not installed — backends {', '.join(sorted(needs_transformers))} won't work"
            )

    if not needs_torch:
        print(
            f"[deps] skipping --collect-all torch/transformers  (backends: {', '.join(sorted(backends))})"
        )

    return candidates


