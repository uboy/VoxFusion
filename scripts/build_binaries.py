def _install_dependencies() -> None:
    """Install all project dependencies into the current Python environment.

    Uses ``pip install`` with the project's ``pyproject.toml``-declared
    requirements so the PyInstaller bundle contains every needed package.
    Prefer poetry if available; fall back to plain pip.
    """
    print("\n[deps] Installing / verifying project dependencies...")

    # Determine platform-specific extras
    extras = []
    if platform.system().lower() == "windows":
        extras.append("windows")

    # Only use poetry when the script itself is already running inside the
    # poetry-managed environment. Otherwise `poetry install` may populate a
    # different interpreter than the one that later runs PyInstaller.
    if shutil.which("poetry") and os.environ.get("POETRY_ACTIVE") == "1":
        cmd = ["poetry", "install", "--no-interaction"]
        print(f"[deps] {' '.join(cmd)}")
        result = subprocess.run(cmd, cwd=PROJECT_ROOT, check=False)
        if result.returncode == 0:
            print("[deps] poetry install succeeded.")
            return
        print("[deps] poetry install failed — falling back to pip.")
    elif shutil.which("poetry"):
        print(
            "[deps] poetry detected but this script is not running inside `poetry run`.\n"
            "[deps] Installing into the current interpreter via pip to keep build/install environments aligned."
        )

    # Fall back to pip install -e .
    extra_str = f"[{','.join(extras)}]" if extras else ""
    pip_cmd = [
        sys.executable,
        "-m",
        "pip",
        "install",
        "--upgrade",
        f".{extra_str}",
    ]
    print(f"[deps] {' '.join(pip_cmd)}")
    result = subprocess.run(pip_cmd, cwd=PROJECT_ROOT, check=False)
    if result.returncode != 0:
        print("[deps] WARNING: pip install returned non-zero. Continuing anyway.")

    print("[deps] Dependency installation complete.\n")


def _generate_icons() -> None:
    """Generate application icons via scripts/make_icon.py (requires Pillow)."""
    try:
        from PIL import Image, ImageDraw  # noqa: F401
    except ImportError:
        print("[icon] Pillow not installed — skipping icon generation (pip install Pillow)")
        return

    make_icon = Path(__file__).resolve().parent / "make_icon.py"
    if not make_icon.exists():
        print(f"[icon] {make_icon} not found — skipping")
        return

    import importlib.util

    spec = importlib.util.spec_from_file_location("make_icon", make_icon)
    mod = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    mod.main()


def _get_icon_path() -> Path | None:
    """Return the platform-specific icon path, generating icons first if needed."""
    system = platform.system().lower()
    name = _ICON_FILES.get(system)
    preferred = ASSETS_DIR / name if name else None

    if preferred and preferred.exists():
        return preferred

    # Icons missing — generate them on the fly
    _generate_icons()

    if preferred and preferred.exists():
        return preferred
    ico = ASSETS_DIR / "voxfusion.ico"
    if ico.exists():
        return ico

    print("[icon] WARNING: icon generation failed — building without icon")
    return None


def _find_ffmpeg_binary() -> Path | None:
    """Locate the ffmpeg binary in PATH for optional bundling."""
    import shutil

    binary_name = "ffmpeg.exe" if platform.system().lower() == "windows" else "ffmpeg"
    found = shutil.which(binary_name) or shutil.which("ffmpeg")
    return Path(found).resolve() if found else None


def _find_7z_executable() -> str | None:
    for candidate in ("7z", "7za"):
        found = shutil.which(candidate)
        if found:
            return found
    return None


def _extract_ffmpeg_binaries_from_zip(zip_path: Path, target_dir: Path) -> Path:
    """Extract `ffmpeg(.exe)`, `ffprobe(.exe)`, and shared DLLs from a ZIP."""
    target_dir.mkdir(parents=True, exist_ok=True)
    ffmpeg_path: Path | None = None
    with zipfile.ZipFile(zip_path) as archive:
        members = {name.lower(): name for name in archive.namelist()}
        for lowered, member in members.items():
            if (
                not lowered.endswith(".dll")
                and not lowered.endswith("/bin/ffmpeg.exe")
                and not lowered.endswith("/bin/ffprobe.exe")
            ):
                continue
            output_path = target_dir / Path(member).name
            with archive.open(member) as src, output_path.open("wb") as dst:
                shutil.copyfileobj(src, dst)
            if output_path.name.lower() == "ffmpeg.exe":
                ffmpeg_path = output_path
    if ffmpeg_path is None or not ffmpeg_path.exists():
        raise RuntimeError("Downloaded FFmpeg archive did not contain bin/ffmpeg.exe")
    return ffmpeg_path


def _extract_ffmpeg_binaries_from_7z(archive_path: Path, target_dir: Path) -> Path:
    """Extract FFmpeg binaries and shared DLLs from a 7z archive."""
    target_dir.mkdir(parents=True, exist_ok=True)
    extractor = _find_7z_executable()
    if extractor is None:
        raise RuntimeError("7z/7za is required to unpack the shared FFmpeg archive")

    command = [
        extractor,
        "e",
        "-y",
        f"-o{target_dir}",
        str(archive_path),
        "*/bin/ffmpeg.exe",
        "*/bin/ffprobe.exe",
        "*/bin/*.dll",
    ]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or result.stdout.strip() or "7z extraction failed")

    ffmpeg_path = target_dir / "ffmpeg.exe"
    if not ffmpeg_path.exists():
        raise RuntimeError("Downloaded FFmpeg archive did not contain bin/ffmpeg.exe")
    return ffmpeg_path


def _extract_ffmpeg_binaries(archive_path: Path, target_dir: Path) -> Path:
    if archive_path.suffix.lower() == ".zip":
        return _extract_ffmpeg_binaries_from_zip(archive_path, target_dir)
    if archive_path.suffix.lower() == ".7z":
        return _extract_ffmpeg_binaries_from_7z(archive_path, target_dir)
    raise RuntimeError(f"Unsupported FFmpeg archive format: {archive_path.suffix}")


def _ensure_windows_ffmpeg_binary() -> Path | None:
    """Download/extract a portable Windows FFmpeg if PATH does not provide one."""
    if platform.system().lower() != "windows":
        return None

    vendor_ffmpeg = FFMPEG_VENDOR_DIR / "ffmpeg.exe"
    if vendor_ffmpeg.exists():
        return vendor_ffmpeg

    FFMPEG_VENDOR_DIR.mkdir(parents=True, exist_ok=True)
    archives = [
        (
            FFMPEG_VENDOR_DIR / "ffmpeg-release-full-shared.7z",
            WINDOWS_FFMPEG_SHARED_URL,
            "[ffmpeg] PATH is missing FFmpeg — downloading shared portable build for bundling...",
        ),
        (
            FFMPEG_VENDOR_DIR / "ffmpeg-release-essentials.zip",
            WINDOWS_FFMPEG_ESSENTIALS_URL,
            "[ffmpeg] PATH is missing FFmpeg — downloading portable build for bundling...",
        ),
    ]

    last_error: Exception | None = None
    for archive_path, url, message in archives:
        try:
            if not archive_path.exists():
                print(message)
                with urllib.request.urlopen(url, timeout=120) as response:
                    archive_path.write_bytes(response.read())
            ffmpeg = _extract_ffmpeg_binaries(archive_path, FFMPEG_VENDOR_DIR)
            print(f"[ffmpeg] prepared portable FFmpeg at {ffmpeg}")
            return ffmpeg
        except Exception as exc:
            last_error = exc
            print(f"[ffmpeg] WARNING: failed to prepare {archive_path.name}: {exc}")
    if last_error is not None:
        raise last_error
    return None


def _detect_linux_distro() -> str:
    """Detect the Linux distribution ID from /etc/os-release."""
    os_release = Path("/etc/os-release")
    if os_release.exists():
        for line in os_release.read_text(encoding="utf-8").splitlines():
            if line.startswith("ID="):
                return line.split("=", 1)[1].strip('"').strip("'").lower()
    return "unknown"


