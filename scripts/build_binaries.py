def _ensure_linux_ffmpeg_binary() -> Path | None:
    """Download a static FFmpeg build for Linux if PATH doesn't provide one."""
    machine = platform.machine().lower()
    arch_map: dict[str, str] = {
        "x86_64": "amd64",
        "amd64": "amd64",
        "aarch64": "arm64",
        "arm64": "arm64",
        "armv7l": "armhf",
        "armhf": "armhf",
    }
    arch = arch_map.get(machine)
    if not arch:
        print(f"[ffmpeg] No static build available for architecture: {machine}")
        return None

    FFMPEG_VENDOR_DIR.mkdir(parents=True, exist_ok=True)
    vendor_ffmpeg = FFMPEG_VENDOR_DIR / "ffmpeg"
    if vendor_ffmpeg.exists():
        print(f"[ffmpeg] using cached static build at {vendor_ffmpeg}")
        return vendor_ffmpeg

    url = LINUX_FFMPEG_STATIC_URL.format(arch=arch)
    archive_path = FFMPEG_VENDOR_DIR / f"ffmpeg-{arch}-static.tar.xz"
    print(f"[ffmpeg] Downloading static FFmpeg for Linux {arch}...")
    try:
        with urllib.request.urlopen(url, timeout=180) as response:
            archive_path.write_bytes(response.read())
    except Exception as exc:
        print(f"[ffmpeg] WARNING: failed to download: {exc}")
        return None

    # Extract ffmpeg and ffprobe from the archive.
    import tarfile

    try:
        with tarfile.open(archive_path) as tar:
            for member in tar.getmembers():
                name = Path(member.name).name
                if name in ("ffmpeg", "ffprobe") and not member.isdir():
                    dest = FFMPEG_VENDOR_DIR / name
                    src_file = tar.extractfile(member)
                    if src_file:
                        with src_file, dest.open("wb") as dst:
                            shutil.copyfileobj(src_file, dst)
                        dest.chmod(0o755)
    except Exception as exc:
        print(f"[ffmpeg] WARNING: failed to extract archive: {exc}")
        return None

    if vendor_ffmpeg.exists():
        print(f"[ffmpeg] prepared static FFmpeg at {vendor_ffmpeg}")
        return vendor_ffmpeg

    print("[ffmpeg] WARNING: ffmpeg binary not found in downloaded archive")
    return None


def _ensure_macos_ffmpeg_binary() -> Path | None:
    """Download FFmpeg for macOS if PATH and Homebrew don't provide one."""
    # Check Homebrew first
    brew = shutil.which("brew")
    if brew:
        result = subprocess.run(
            ["brew", "--prefix", "ffmpeg"],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode == 0:
            ffmpeg = Path(result.stdout.strip()) / "bin" / "ffmpeg"
            if ffmpeg.exists():
                print(f"[ffmpeg] found Homebrew FFmpeg at {ffmpeg}")
                return ffmpeg

    FFMPEG_VENDOR_DIR.mkdir(parents=True, exist_ok=True)
    vendor_ffmpeg = FFMPEG_VENDOR_DIR / "ffmpeg"
    if vendor_ffmpeg.exists():
        print(f"[ffmpeg] using cached build at {vendor_ffmpeg}")
        return vendor_ffmpeg

    # Try downloading from evermeet.cx
    import io

    print("[ffmpeg] Downloading FFmpeg for macOS...")
    try:
        url = MACOS_FFMPEG_URL.format(binary="ffmpeg")
        with urllib.request.urlopen(url, timeout=120) as response:
            data = response.read()

        with zipfile.ZipFile(io.BytesIO(data)) as zf:
            for name in zf.namelist():
                if Path(name).name.lower() == "ffmpeg":
                    with zf.open(name) as src, vendor_ffmpeg.open("wb") as dst:
                        shutil.copyfileobj(src, dst)
                    vendor_ffmpeg.chmod(0o755)
                    break

        if not vendor_ffmpeg.exists():
            print("[ffmpeg] WARNING: ffmpeg binary not found in downloaded archive")
            return None

        # Also download ffprobe
        try:
            vendor_ffprobe = FFMPEG_VENDOR_DIR / "ffprobe"
            url_probe = MACOS_FFMPEG_URL.format(binary="ffprobe")
            with urllib.request.urlopen(url_probe, timeout=120) as response:
                data = response.read()
            with zipfile.ZipFile(io.BytesIO(data)) as zf:
                for name in zf.namelist():
                    if Path(name).name.lower() == "ffprobe":
                        with zf.open(name) as src, vendor_ffprobe.open("wb") as dst:
                            shutil.copyfileobj(src, dst)
                        vendor_ffprobe.chmod(0o755)
                        break
        except Exception:
            pass  # ffprobe is optional

        print(f"[ffmpeg] prepared FFmpeg at {vendor_ffmpeg}")
        return vendor_ffmpeg
    except Exception as exc:
        print(f"[ffmpeg] WARNING: failed to download FFmpeg: {exc}")
        return None


def _ffmpeg_data_entries() -> list[str]:
    """Return data entries for bundling FFmpeg/FFprobe into the app root."""
    ffmpeg = _find_ffmpeg_binary()
    if ffmpeg and ffmpeg.exists():
        print(f"[ffmpeg] bundling {ffmpeg}")
    else:
        system = platform.system().lower()
        try:
            if system == "windows":
                ffmpeg = _ensure_windows_ffmpeg_binary()
            elif system == "linux":
                ffmpeg = _ensure_linux_ffmpeg_binary()
            elif system == "darwin":
                ffmpeg = _ensure_macos_ffmpeg_binary()
        except Exception as exc:
            ffmpeg = None
            print(f"[ffmpeg] WARNING: failed to prepare FFmpeg: {exc}")

    if ffmpeg is None or not ffmpeg.exists():
        _show_ffmpeg_install_hint()
        return []

    entries = [f"{ffmpeg}{os.pathsep}."]
    ffprobe = ffmpeg.with_name("ffprobe.exe" if ffmpeg.suffix.lower() == ".exe" else "ffprobe")
    if ffprobe.exists():
        entries.append(f"{ffprobe}{os.pathsep}.")
    for dll in sorted(ffmpeg.parent.glob("*.dll")):
        entries.append(f"{dll}{os.pathsep}.")
    return entries


def _customtkinter_data_entries() -> list[str]:
    """Collect customtkinter theme paths when package is installed."""
    try:
        import customtkinter  # type: ignore[import-not-found]
    except ImportError:
        return []

    package_root = Path(customtkinter.__file__).resolve().parent
    themes_dir = package_root / "assets" / "themes"
    if not themes_dir.exists():
        return []

    return [f"{themes_dir}{os.pathsep}customtkinter/assets/themes"]


def _pyannote_data_entries() -> list[str]:
    """Collect pyannote runtime data files required in frozen bundles."""
    spec = _safe_find_spec("pyannote.audio.telemetry")
    if spec is None or spec.origin is None:
        return []

    telemetry_dir = Path(spec.origin).resolve().parent
    config_path = telemetry_dir / "config.yaml"
    if not config_path.exists():
        print(
            "[deps] WARNING: pyannote telemetry config.yaml not found, ML diarization bundle may be incomplete"
        )
        return []

    return [f"{config_path}{os.pathsep}pyannote/audio/telemetry"]


def _package_file_data_entry(package_name: str, filename: str) -> str | None:
    """Return an ``--add-data`` entry for a package-local file when present."""
    spec = _safe_find_spec(package_name)
    if spec is None or spec.origin is None:
        return None

    package_dir = Path(spec.origin).resolve().parent
    file_path = package_dir / filename
    if not file_path.exists():
        print(
            f"[deps] WARNING: {package_name}/{filename} not found, frozen bundle may be incomplete"
        )
        return None

    target_dir = package_name.replace(".", "/")
    return f"{file_path}{os.pathsep}{target_dir}"


def _default_data_entries() -> list[str]:
    defaults_yaml = PROJECT_ROOT / "src" / "voxfusion" / "config" / "defaults.yaml"
    gui_locales_dir = PROJECT_ROOT / "src" / "voxfusion" / "gui" / "locales"
    entries = [f"{defaults_yaml}{os.pathsep}voxfusion/config"]
    if gui_locales_dir.exists():
        entries.append(f"{gui_locales_dir}{os.pathsep}voxfusion/gui/locales")
    else:
        print(
            "[deps] WARNING: GUI locales directory not found, frozen GUI may fall back to raw i18n keys"
        )
    entries.extend(_customtkinter_data_entries())
    entries.extend(_pyannote_data_entries())
    # lightning version files are only needed when torch backends are bundled;
    # collecting them triggers PyInstaller's isolated subprocess analysis which
    # segfaults when torch.distributed is imported transitively on Linux.
    # entries.extend(_package_file_data_entry(...) for lightning packages)
    entries.extend(_ffmpeg_data_entries())
    return entries


def _platform_tag() -> str:
    machine = platform.machine().lower() or "unknown"
    system_name = platform.system().lower() or "unknown"
    return f"{system_name}-{machine}"


def _copy_python_dll(bundle_dir: Path) -> None:
    """Copy python3XX.dll next to the EXE for reliable loading on Windows.

    PyInstaller places the DLL in _internal/ and uses SetDllDirectory to
    expose it, but some Windows 11 security configurations prevent this.
    Having the DLL in the same directory as the EXE is always found first
    by the Windows DLL loader without any extra API calls.
    """
    if platform.system().lower() != "windows":
        return
    dll_name = f"python{sys.version_info.major}{sys.version_info.minor}.dll"
    src = Path(sys.executable).parent / dll_name
    if not src.exists():
        print(f"[dll] WARNING: {dll_name} not found at {src}, skipping copy")
        return
    dst = bundle_dir / dll_name
    if not dst.exists():
        shutil.copy2(src, dst)
        print(f"[dll] copied {dll_name} to bundle root for reliable loading")


def build_target(
    target: BinaryTarget,
    *,
    version_file: Path,
    include_zip: bool,
    backends: set[str],
) -> Path:
    """Build one binary target and optionally package to ZIP."""
    DIST_DIR.mkdir(parents=True, exist_ok=True)
    pyinstaller_work = BUILD_DIR / "pyinstaller-work" / target.name
    pyinstaller_spec = BUILD_DIR / "pyinstaller-spec"
    pyinstaller_work.mkdir(parents=True, exist_ok=True)
    pyinstaller_spec.mkdir(parents=True, exist_ok=True)

    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onedir",
        "--name",
        target.name,
        "--distpath",
        str(DIST_DIR),
        "--workpath",
        str(pyinstaller_work),
        "--specpath",
        str(pyinstaller_spec),
    ]
    command.extend(["--paths", str(PROJECT_ROOT / "src")])

    if platform.system().lower() == "windows" and version_file.exists():
        command.extend(["--version-file", str(version_file)])

    icon = _get_icon_path()
    if icon:
        command.extend(["--icon", str(icon)])
        print(f"[icon] {icon}")
    else:
        print(
            "[icon] WARNING: no icon found in assets/.\n"
            "  Run: python scripts/make_icon.py   (requires: pip install Pillow)"
        )

    command.append("--windowed" if target.windowed else "--console")

    # Exclude torch submodules that crash PyInstaller's submodule collection
    # with SIGSEGV during _collect_submodules(). These are not needed for
    # inference (only for distributed training).
    for exclude in (
        "torch.distributed",
        "torch.testing",
        "torch._C._distributed_c10d",
    ):
        command.extend(["--exclude-module", exclude])

    # Disable PyInstaller's built-in hook for torch which triggers a segfault
    # when collecting torch.distributed.optim submodules on Linux.
    # Use custom hook directory with a safe torch hook override.
    custom_hooks = PROJECT_ROOT / "scripts" / "pyinstaller-hooks"
    if custom_hooks.is_dir():
        command.extend(["--additional-hooks-dir", str(custom_hooks)])

    for imp in _hidden_imports(backends=backends):
        command.extend(["--hidden-import", imp])

    # Collect all files (including native DLLs) from packages that need it.
    # Only packages that are actually installed are included.
    for pkg in _collect_all_packages(backends=backends):
        command.extend(["--collect-all", pkg])

    for entry in _default_data_entries():
        command.extend(["--add-data", entry])

    launcher = _write_launcher(target)
    command.append(str(launcher))

    print(f"\n[build] {target.name}")
    print(" ".join(command))
    subprocess.run(command, cwd=PROJECT_ROOT, check=True)

    bundle_dir = DIST_DIR / target.name
    _copy_python_dll(bundle_dir)
    if not include_zip:
        return bundle_dir

    archive_basename = DIST_DIR / f"{target.name}-{_platform_tag()}"
    zip_path = archive_basename.with_suffix(".zip")
    if zip_path.exists():
        zip_path.unlink()

    shutil.make_archive(
        base_name=str(archive_basename),
        format="zip",
        root_dir=str(DIST_DIR),
        base_dir=target.name,
    )
    print(f"[zip] {zip_path}")
    return zip_path


def main() -> int:
    """Main build flow."""
    args = parse_args()

    if not args.skip_install:
        _install_dependencies()
    else:
        print("[deps] Skipping dependency installation (--skip-install).")

    version, version_tuple = load_version()
    version_file = write_version_file(
        company_name=args.company_name,
        product_name=args.product_name,
        version_str=version,
        version_tuple=version_tuple,
    )

    selected_targets: list[BinaryTarget]
    if args.target == "all":
        selected_targets = [TARGETS["gui"], TARGETS["cli"]]
    else:
        selected_targets = [TARGETS[args.target]]

    backends = _parse_backends(args.backends)
    print(f"[backends] building with: {', '.join(sorted(backends))}")

    for target in selected_targets:
        build_target(
            target,
            version_file=version_file,
            include_zip=not args.no_zip,
            backends=backends,
        )

    print("\nBuild completed.")
    if platform.system().lower() == "windows":
        print(
            "Windows note: ask users to open ZIP file properties and click "
            "'Unblock' before extraction."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
